//! Name resolution inside the sandbox.
//!
//! There is no DNS: only literal addresses are approved. `--host NAME=ADDR`
//! entries, and with `--pass-hosts` the `hostname` of each single-address
//! destination of the pass in use, go into a generated hosts file, and the
//! DNS stub on `127.0.0.1` port 53 (see [`crate::dns_stub`]) answers the
//! same names and says every other name does not exist. Nothing is looked
//! up. The generated `resolv.conf` names that stub as the only nameserver.
//! The generated `nsswitch.conf` keeps the host's file but sets
//! `hosts: files dns`, so glibc never asks a host daemon (systemd-resolved,
//! nscd, avahi) that would resolve the name on the host's network: `dns`
//! sends its queries to the nameserver in `resolv.conf`, inside the
//! sandbox's own network namespace.

use std::fmt::Write as _;
use std::net::IpAddr;

use crate::approval::{Approval, SpecError, parse_literal_addr};

/// One `--host NAME=ADDR` entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HostEntry {
    /// Host name, checked to contain only letters, digits, `-` and `.`.
    pub name: String,
    /// The literal address the name resolves to.
    pub addr: IpAddr,
}

/// Parses `NAME=ADDR`.
///
/// # Errors
/// When the name is not a plain host name or the address is not literal.
pub fn parse_host(text: &str) -> Result<HostEntry, SpecError> {
    let wrap = |m: String| SpecError::from_message(format!("--host {text:?}: {m}"));
    let (name, addr) = text
        .split_once('=')
        .ok_or_else(|| wrap("expected NAME=ADDR, for example example.test=192.0.2.10".into()))?;
    if !valid_hostname(name) {
        return Err(wrap(format!(
            "{name:?} is not a plain host name (letters, digits, '-' and '.', at most 253 characters)"
        )));
    }
    if let Some(v4) = addr
        .strip_prefix('[')
        .and_then(|a| a.strip_suffix(']'))
        .filter(|a| !a.contains(':'))
    {
        return Err(wrap(format!(
            "brackets are for IPv6 addresses only; write {name}={v4}"
        )));
    }
    let addr = parse_literal_addr(addr).map_err(|e| wrap(e.to_string()))?;
    Ok(HostEntry {
        name: name.to_ascii_lowercase(),
        addr,
    })
}

/// Whether `name` is a host name we are willing to write into a hosts file.
#[must_use]
pub fn valid_hostname(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 253
        && name.split('.').all(|label| {
            !label.is_empty()
                && label.len() <= 63
                && label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-')
                && !label.starts_with('-')
                && !label.ends_with('-')
        })
        && !name.bytes().all(|b| b.is_ascii_digit() || b == b'.')
}

/// Checks every host entry points at an approved address.
///
/// # Errors
/// When an entry's address is not covered by any allow rule.
pub fn check_hosts(hosts: &[HostEntry], approval: &Approval) -> Result<(), SpecError> {
    for h in hosts {
        if !approval.covers_addr(h.addr) {
            return Err(SpecError::from_message(format!(
                "--host {}={}: {} is not covered by any --allow, so the name would lead nowhere; approve the address first{}",
                h.name,
                h.addr,
                h.addr,
                approval.edge_hint(h.addr)
            )));
        }
    }
    Ok(())
}

/// The generated `/etc/hosts`.
#[must_use]
pub fn hosts_file(hosts: &[HostEntry], own_hostname: Option<&str>) -> String {
    let mut out = String::from(
        "# generated by playpen: only names given with --host or --pass-hosts resolve\n",
    );
    let own = own_hostname.filter(|h| valid_hostname(h));
    match own {
        Some(h) => {
            let _ = writeln!(out, "127.0.0.1\tlocalhost {h}");
            let _ = writeln!(out, "::1\tlocalhost {h}");
        }
        None => {
            out.push_str("127.0.0.1\tlocalhost\n::1\tlocalhost\n");
        }
    }
    for h in hosts {
        let _ = writeln!(out, "{}\t{}", h.addr, h.name);
    }
    out
}

/// The generated `/etc/resolv.conf`: the DNS stub is the only nameserver.
///
/// `search .` is an empty search list: without it, glibc takes the domain
/// of the machine's host name as one, and a lookup of `a.example` on
/// `box.lan` also asks for `a.example.lan`.
#[must_use]
pub fn resolv_conf() -> String {
    format!(
        "# generated by playpen: there is no DNS inside the sandbox\n# names given with --host or --pass-hosts are in /etc/hosts; the stub at {} answers\n# them too, says every other name does not exist, and forwards nothing\nnameserver {}\nsearch .\noptions timeout:1 attempts:1\n",
        crate::dns_stub::ADDRESS,
        crate::dns_stub::ADDRESS
    )
}

/// The `hosts:` line of the generated `nsswitch.conf`.
const HOSTS_LINE: &str = "hosts: files dns\n";

/// The host's `nsswitch.conf` with the `hosts:` line replaced by
/// `hosts: files dns`.
#[must_use]
pub fn nsswitch_conf(original: &str) -> String {
    let mut out =
        String::from("# generated by playpen from the host's file; hosts: files, then the stub\n");
    // The `dns` source asks only the nameserver in the generated
    // resolv.conf, over the sandbox's own loopback. The host's other
    // sources (resolve, mdns, mymachines, myhostname) are left out.
    let mut saw_hosts = false;
    for line in original.lines() {
        if line.trim_start().starts_with("hosts:") {
            out.push_str(HOSTS_LINE);
            saw_hosts = true;
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    if !saw_hosts {
        out.push_str(HOSTS_LINE);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::approval::parse_allow;

    #[test]
    fn parses_host_entries() {
        let h = parse_host("Example.Test=192.0.2.10").unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(h.name, "example.test");
        assert!(parse_host("example.test=[2001:db8::10]").is_ok());
        let err = parse_host("a.test=[192.0.2.1]")
            .err()
            .map_or_else(String::new, |e| e.to_string());
        assert!(err.contains("write a.test=192.0.2.1"), "{err}");
        assert!(parse_host("example.test").is_err());
        assert!(parse_host("example.test=other.test").is_err());
        assert!(parse_host("bad name=192.0.2.1").is_err());
        assert!(parse_host("evil\n192.0.2.9 x=192.0.2.1").is_err());
        assert!(parse_host("a#b=192.0.2.1").is_err());
        assert!(parse_host("-x.test=192.0.2.1").is_err());
        assert!(parse_host("192.0.2.1=192.0.2.1").is_err());
        assert!(parse_host("=192.0.2.1").is_err());
        assert!(parse_host("x.test=192.0.2.01").is_err());
    }

    #[test]
    fn hosts_must_be_approved() {
        let approval = Approval::new(
            vec![parse_allow("192.0.2.0/24:443/tcp").unwrap_or_else(|e| panic!("{e}"))],
            None,
        );
        let ok = parse_host("a.test=192.0.2.10").unwrap_or_else(|e| panic!("{e}"));
        let bad = parse_host("b.test=198.51.100.1").unwrap_or_else(|e| panic!("{e}"));
        assert!(check_hosts(std::slice::from_ref(&ok), &approval).is_ok());
        let err = check_hosts(&[ok, bad], &approval)
            .err()
            .map(|e| e.to_string());
        assert!(err.unwrap_or_default().contains("not covered"));
    }

    #[test]
    fn generated_files() {
        let h = parse_host("a.test=192.0.2.10").unwrap_or_else(|e| panic!("{e}"));
        let text = hosts_file(&[h], Some("box"));
        assert!(text.contains("192.0.2.10\ta.test\n"));
        assert!(text.contains("127.0.0.1\tlocalhost box\n"));
        assert!(!hosts_file(&[], Some("bad host")).contains("bad host"));
        let resolv = resolv_conf();
        let nameservers: Vec<&str> = resolv
            .lines()
            .filter(|l| l.starts_with("nameserver"))
            .collect();
        assert_eq!(nameservers, ["nameserver 127.0.0.1"]);
        assert!(resolv.contains("\nsearch .\n"));
        assert!(resolv.contains("\noptions timeout:1 attempts:1\n"));
        let ns = nsswitch_conf(
            "passwd: files systemd\nhosts: mymachines mdns_minimal resolve [!UNAVAIL=return] files myhostname dns\n",
        );
        assert!(ns.contains("passwd: files systemd\n"));
        assert!(ns.contains("\nhosts: files dns\n"));
        for gone in ["resolve", "mdns", "mymachines", "myhostname"] {
            assert!(!ns.contains(gone), "{ns}");
        }
        assert!(nsswitch_conf("passwd: files\n").ends_with("hosts: files dns\n"));
    }
}
